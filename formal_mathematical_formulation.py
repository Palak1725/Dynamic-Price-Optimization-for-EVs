import pandas as pd
import numpy as np
import os
import joblib

from hmmlearn.hmm import GaussianHMM


# ==========================================
# PHASE 4.1: FORMAL HMM MATHEMATICAL FORMULATION
# ==========================================


# ==========================================
# STEP 1: LOAD ORIGINAL HOURLY FEATURES
# ==========================================

training_url = (
    "https://raw.githubusercontent.com/theshreyaaa/"
    "Dynamic-price-optimization-for-electric-vehicle-EV-technology/"
    "main/ev_charging_hourly_features.csv"
)

training_df = pd.read_csv(training_url)

training_df["timestamp"] = pd.to_datetime(
    training_df["timestamp"]
)

training_df = training_df.sort_values(
    "timestamp"
).reset_index(drop=True)

print("Dataset loaded successfully!")
print("Dataset shape:", training_df.shape)

print("\nColumns:")
print(training_df.columns.tolist())

print("\nMissing values:")
print(training_df.isnull().sum())

assert not training_df.isnull().any().any(), (
    "Dataset contains missing values."
)


# ==========================================
# STEP 2: DEFINE OBSERVATION VECTOR
# ==========================================

# Observation vector:
# o_t = [occupancy_rate, transformer_load_ratio]

feature_columns = [
    "occupancy_rate",
    "transformer_load_ratio"
]

X = training_df[feature_columns].values

assert np.isfinite(X).all(), (
    "Observation data contains non-finite values."
)

print("\nObservation matrix shape:", X.shape)
print("Number of observations:", len(X))
print("Number of observed features:", X.shape[1])


# ==========================================
# STEP 3: DEFINE HIDDEN STATES
# ==========================================

# Three hidden operating regimes:
# S1 = Surplus
# S2 = Nominal
# S3 = Peak Stress

N_STATES = 3

labels = {
    0: "Surplus",
    1: "Nominal",
    2: "Peak Stress"
}

state_names = [
    "Surplus",
    "Nominal",
    "Peak Stress"
]

print("\nHidden states:")
for k in range(N_STATES):
    print(f"S{k+1}: {labels[k]}")


# ==========================================
# STEP 4: TRAIN GAUSSIAN HMM
# ==========================================

model = GaussianHMM(
    n_components=N_STATES,
    covariance_type="full",
    n_iter=200,
    random_state=42
)

model.fit(X)

print("\nHMM training completed!")

print("\nOriginal Transition Matrix:")
print(np.round(model.transmat_, 6))

print("\nOriginal Initial Probabilities:")
print(np.round(model.startprob_, 6))

print("\nOriginal Emission Means:")
print(np.round(model.means_, 6))

print("\nOriginal Covariance Matrices:")
print(np.round(model.covars_, 6))


# ==========================================
# STEP 5: ORDER HIDDEN STATES
# ==========================================

# Order states by average transformer load.
# Lowest = Surplus
# Middle = Nominal
# Highest = Peak Stress

order = np.argsort(model.means_[:, 1])

print("\nState ordering:", order)

# Create mapping from original state IDs
# to ordered state IDs.

rank = np.empty_like(order)
rank[order] = np.arange(N_STATES)


# ==========================================
# STEP 6: REORDER HMM PARAMETERS
# ==========================================

ordered_startprob = model.startprob_[order].copy()

ordered_transmat = model.transmat_[
    np.ix_(order, order)
].copy()

ordered_means = model.means_[order].copy()

ordered_covars = model.covars_[order].copy()


print("\nOrdered Initial Probabilities:")
print(np.round(ordered_startprob, 6))

print("\nOrdered Theoretical Transition Matrix:")
print(np.round(ordered_transmat, 6))

print("\nOrdered Emission Means:")
print(np.round(ordered_means, 6))

print("\nOrdered Covariance Matrices:")
print(np.round(ordered_covars, 6))


# ==========================================
# STEP 7: ASSIGN ORDERED PARAMETERS
# BACK TO THE MODEL
# ==========================================

# Important:
# The saved model must use the same state ordering
# as the labels and exported transition matrix.

model.startprob_ = ordered_startprob.copy()

model.transmat_ = ordered_transmat.copy()

model.means_ = ordered_means.copy()

model.covars_ = ordered_covars.copy()

print("\nOrdered parameters assigned to HMM model.")


# ==========================================
# STEP 8: DECODE ORDERED HIDDEN STATES
# ==========================================

# Since the model parameters are now ordered,
# its predicted state IDs directly match:
# 0 = Surplus
# 1 = Nominal
# 2 = Peak Stress

named_states = model.predict(X)

print("\nDecoded states successfully!")

state_counts = pd.Series(
    named_states
).value_counts().reindex(
    range(N_STATES),
    fill_value=0
)

print("\nOperating Regime Distribution:")

for k in range(N_STATES):
    print(
        f"{labels[k]}: {state_counts[k]} hours "
        f"({state_counts[k] / len(X) * 100:.2f}%)"
    )


# ==========================================
# STEP 9: HMM PARAMETER VALIDATION
# ==========================================

print("\n========== PHASE 4.1.3 ==========")
print("HMM PARAMETER VALIDATION")


# 1. Validate transition matrix row sums

print("\nTransition matrix row sums:")
print(model.transmat_.sum(axis=1))

assert np.allclose(
    model.transmat_.sum(axis=1),
    1.0
)


# 2. Validate initial probabilities

print("\nInitial probability sum:")
print(model.startprob_.sum())

assert np.isclose(
    model.startprob_.sum(),
    1.0
)


# 3. Validate covariance matrix symmetry

print("\nCovariance matrix symmetry:")

for k in range(N_STATES):

    symmetric = np.allclose(
        model.covars_[k],
        model.covars_[k].T,
        atol=1e-10
    )

    print(f"{labels[k]}: {symmetric}")

    assert symmetric, (
        f"{labels[k]} covariance matrix is not symmetric."
    )


# 4. Validate covariance positive definiteness

print("\nCovariance matrix eigenvalues:")

for k in range(N_STATES):

    eigenvalues = np.linalg.eigvalsh(
        model.covars_[k]
    )

    print(f"{labels[k]}:", eigenvalues)

    assert np.all(eigenvalues > 0), (
        f"{labels[k]} covariance matrix is not positive definite."
    )


# 5. Validate parameter dimensions

assert model.transmat_.shape == (3, 3)

assert model.startprob_.shape == (3,)

assert model.means_.shape == (3, 2)

assert model.covars_.shape == (3, 2, 2)

print("\nALL HMM PARAMETER VALIDATIONS PASSED!")


# ==========================================
# STEP 10: EMPIRICAL TRANSITION MATRIX
# ==========================================

print("\n========== EMPIRICAL TRANSITION ANALYSIS ==========")

previous_states = named_states[:-1]

next_states = named_states[1:]


# Calculate empirical transition counts

empirical_counts = pd.crosstab(
    pd.Series(previous_states, name="Current State"),
    pd.Series(next_states, name="Next State")
)

empirical_counts = empirical_counts.reindex(
    index=range(N_STATES),
    columns=range(N_STATES),
    fill_value=0
)

empirical_counts.index = state_names
empirical_counts.columns = state_names

print("\nEmpirical Transition Counts:")
print(empirical_counts)


# Calculate empirical transition probabilities

row_totals = empirical_counts.sum(axis=1)

empirical_probabilities = empirical_counts.div(
    row_totals.replace(0, np.nan),
    axis=0
).fillna(0)

print("\nEmpirical Transition Probability Matrix:")
print(empirical_probabilities.round(6))

print(
    "\nTotal empirical transitions:",
    empirical_counts.values.sum()
)

print("\nEmpirical transition row sums:")
print(empirical_probabilities.sum(axis=1).round(6))


# ==========================================
# STEP 11: THEORETICAL TRANSITION MATRIX
# ==========================================

# This matrix comes directly from the
# trained and ordered HMM model.

theoretical_transition_matrix = pd.DataFrame(
    model.transmat_,
    index=state_names,
    columns=state_names
)

print("\nTheoretical HMM Transition Matrix:")
print(theoretical_transition_matrix.round(6))


# ==========================================
# STEP 12: STATE PERSISTENCE
# ==========================================

print("\nState Persistence:")

for k in range(N_STATES):

    persistence = model.transmat_[k, k]

    print(
        f"{labels[k]}: {persistence:.6f}"
    )


# ==========================================
# STEP 13: SAVE ALL OUTPUTS
# ==========================================

os.makedirs(
    "trained_models",
    exist_ok=True
)


# 1. Save ordered HMM model

joblib.dump(
    model,
    "trained_models/gaussian_hmm_ordered_v1.pkl"
)


# 2. Save theoretical transition matrix

theoretical_transition_matrix.to_csv(
    "trained_models/theoretical_transition_matrix.csv"
)


# 3. Save empirical transition counts

empirical_counts.to_csv(
    "trained_models/empirical_transition_counts.csv"
)


# 4. Save empirical transition probabilities

empirical_probabilities.to_csv(
    "trained_models/empirical_transition_probability_matrix.csv"
)


# 5. Save initial probabilities

initial_probabilities = pd.DataFrame(
    [model.startprob_],
    columns=state_names
)

initial_probabilities.to_csv(
    "trained_models/initial_state_probabilities.csv",
    index=False
)


# 6. Save emission means

emission_means = pd.DataFrame(
    model.means_,
    index=state_names,
    columns=feature_columns
)

emission_means.to_csv(
    "trained_models/emission_means.csv"
)


# 7. Save emission covariance matrices

np.save(
    "trained_models/emission_covariances.npy",
    model.covars_
)


# 8. Save decoded hourly states

out = training_df.copy()

out["state"] = named_states

out["state_name"] = pd.Series(
    named_states
).map(labels).values

out.to_csv(
    "hourly_features_with_states.csv",
    index=False
)


print("\n==========================================")
print("ALL OUTPUT FILES SAVED SUCCESSFULLY!")
print("==========================================")

print("\nSaved files:")

print("1. trained_models/gaussian_hmm_ordered_v1.pkl")

print("2. trained_models/theoretical_transition_matrix.csv")

print("3. trained_models/empirical_transition_counts.csv")

print("4. trained_models/empirical_transition_probability_matrix.csv")

print("5. trained_models/initial_state_probabilities.csv")

print("6. trained_models/emission_means.csv")

print("7. trained_models/emission_covariances.npy")

print("8. hourly_features_with_states.csv")
