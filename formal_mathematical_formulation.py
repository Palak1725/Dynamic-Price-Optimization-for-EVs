import pandas as pd
import os
import numpy as np
import joblib
from hmmlearn.hmm import GaussianHMM

# ==========================================
# STEP 1: LOAD DATASET
# ==========================================

url = "https://raw.githubusercontent.com/theshreyaaa/Dynamic-price-optimization-for-electric-vehicle-EV-technology/main/hourly_features_with_states.csv"

df = pd.read_csv(url)

print("Dataset loaded successfully!")
print("Dataset shape:", df.shape)
print("\nColumn names:")
print(df.columns.tolist())

print("\nFirst 5 observations:")
print(df.head())


# ==========================================
# STEP 2: VERIFY DATASET
# ==========================================

df["timestamp"] = pd.to_datetime(df["timestamp"])
df = df.sort_values("timestamp").reset_index(drop=True)

print("\nMissing values:")
print(df.isnull().sum())

print("\nTotal observations:", len(df))


# ==========================================
# STEP 3: OPERATING REGIME DISTRIBUTION
# ==========================================

state_counts = df["state_name"].value_counts()

print("\nNumber of hours in each operating regime:")
print(state_counts)

print("\nPercentage distribution:")
print((state_counts / len(df) * 100).round(2))


# ==========================================
# STEP 4: STATE-WISE FEATURE ANALYSIS
# ==========================================

state_analysis = df.groupby("state_name").agg({
    "occupancy_rate": "mean",
    "transformer_load_ratio": "mean"
})

print("\nAverage values for each operating regime:")
print(state_analysis)


# ==========================================
# STEP 5: TRANSITION COUNTS
# ==========================================

current_states = df["state"].iloc[:-1]
next_states = df["state"].shift(-1).iloc[:-1]

state_order = [0, 1, 2]

transition_counts = pd.crosstab(
    current_states,
    next_states
).reindex(
    index=state_order,
    columns=state_order,
    fill_value=0
)

print("\nTransition Counts:")
print(transition_counts)

print("\nTotal transitions:", transition_counts.values.sum())


# ==========================================
# STEP 6: TRANSITION PROBABILITY MATRIX
# ==========================================

transition_matrix = transition_counts.div(
    transition_counts.sum(axis=1),
    axis=0
)

print("\nTransition Probability Matrix:")
print(transition_matrix.round(6))


# ==========================================
# STEP 7: VALIDATION
# ==========================================

print("\nRow sums of transition matrix:")
print(transition_matrix.sum(axis=1))

print("\nValidation:")

if transition_matrix.shape == (3, 3):
    print("PASS: Three operating states verified.")

if transition_counts.values.sum() == len(df) - 1:
    print("PASS: Total transitions verified.")

if all(abs(transition_matrix.sum(axis=1) - 1) < 1e-9):
    print("PASS: Every transition probability row sums to 1.")


# ==========================================
# STEP 8: TRAIN HMM MODEL
# ==========================================

training_url = "https://raw.githubusercontent.com/theshreyaaa/Dynamic-price-optimization-for-electric-vehicle-EV-technology/main/ev_charging_hourly_features.csv"

training_df = pd.read_csv(training_url)

print("\nOriginal training dataset loaded successfully!")
print("Dataset shape:", training_df.shape)
print("Columns:", training_df.columns.tolist())

X = training_df[
    ["occupancy_rate", "transformer_load_ratio"]
].values

model = GaussianHMM(
    n_components=3,
    covariance_type="full",
    n_iter=200,
    random_state=42
)

model.fit(X)


# ==========================================
# STEP 9: EXTRACT HMM PARAMETERS
# ==========================================

print("\nOriginal Transition Matrix:")
print(np.round(model.transmat_, 3))

print("\nEmission means [occupancy, load_ratio]:")
print(np.round(model.means_, 4))

print("\nCovariance matrices:")
print(np.round(model.covars_, 5))

print("\nStarting probabilities:")
print(np.round(model.startprob_, 3))


# ==========================================
# STEP 10: DECODE STATES (VITERBI)
# ==========================================

raw_states = model.predict(X)

# Sort states by average transformer load
# Lowest = Surplus
# Middle = Nominal
# Highest = Peak Stress

order = np.argsort(model.means_[:, 1])

rank = np.empty_like(order)
rank[order] = np.arange(3)

named_states = rank[raw_states]


# ==========================================
# REORDER HMM PARAMETERS
# ==========================================

ordered_transmat = model.transmat_[
    np.ix_(order, order)
]

print("\nOrdered HMM Transition Matrix:")
print(np.round(ordered_transmat, 6))

ordered_startprob = model.startprob_[order]

print("\nOrdered Initial State Probabilities:")
print(np.round(ordered_startprob, 6))

ordered_means = model.means_[order]

print("\nOrdered Emission Means [occupancy, load_ratio]:")
print(np.round(ordered_means, 6))

ordered_covars = model.covars_[order]

print("\nOrdered Covariance Matrices:")
print(np.round(ordered_covars, 6))


# ==========================================
# STATE LABELS
# ==========================================

# Define labels BEFORE using them in validation

labels = {
    0: "Surplus",
    1: "Nominal",
    2: "Peak Stress"
}


# ==========================================
# PHASE 4.1.3: HMM PARAMETER VALIDATION
# ==========================================

print("\n========== PHASE 4.1.3 ==========")
print("HMM PARAMETER VALIDATION")

# 1. Validate transition matrix

print("\nTransition matrix row sums:")
print(ordered_transmat.sum(axis=1))

# 2. Validate initial probabilities

print("\nInitial probability sum:")
print(ordered_startprob.sum())

# 3. Validate covariance matrix symmetry

print("\nCovariance matrix symmetry:")

for k in range(3):
    print(
        f"{labels[k]}:",
        np.allclose(
            ordered_covars[k],
            ordered_covars[k].T
        )
    )

# 4. Validate covariance matrix positive definiteness

print("\nCovariance matrix eigenvalues:")

for k in range(3):
    eigenvalues = np.linalg.eigvalsh(ordered_covars[k])

    print(f"{labels[k]}:", eigenvalues)

    assert np.all(eigenvalues > 0), (
        f"{labels[k]} covariance matrix is not positive definite"
    )

# 5. Final assertions

assert np.allclose(
    ordered_transmat.sum(axis=1), 1
)

assert np.isclose(
    ordered_startprob.sum(), 1
)

assert ordered_transmat.shape == (3, 3)
assert ordered_startprob.shape == (3,)
assert ordered_means.shape == (3, 2)
assert ordered_covars.shape == (3, 2, 2)

print("\nALL HMM PARAMETER VALIDATIONS PASSED!")


# ==========================================
# HOURS SPENT IN EACH STATE
# ==========================================

print("\nHours spent in each state:")

for k in range(3):
    print(
        f"  {labels[k]}: "
        f"{(named_states == k).sum()} hours"
    )


# ==========================================
# STEP 11: PERSISTENCE
# ==========================================

print("\nPersistence (diagonal of transition matrix):")

for k in range(3):
    print(
        f"  {labels[k]}: "
        f"{ordered_transmat[k, k]:.3f}"
    )


# ==========================================
# PHASE 4.1.2: EMPIRICAL TRANSITION MATRIX
# ==========================================

print("\n========== PHASE 4.1.2 ==========")
print("EMPIRICAL TRANSITION PROBABILITY MATRIX")

previous_states = named_states[:-1]
next_states = named_states[1:]

empirical_counts = pd.crosstab(
    pd.Series(previous_states, name="Current State"),
    pd.Series(next_states, name="Next State")
)

empirical_counts = empirical_counts.reindex(
    index=[0, 1, 2],
    columns=[0, 1, 2],
    fill_value=0
)

state_names = ["Surplus", "Nominal", "Peak Stress"]

empirical_counts.index = state_names
empirical_counts.columns = state_names

print("\nEmpirical Transition Counts:")
print(empirical_counts)

row_totals = empirical_counts.sum(axis=1)

empirical_probabilities = empirical_counts.div(
    row_totals.replace(0, np.nan),
    axis=0
).fillna(0)

print("\nEmpirical Transition Probability Matrix:")
print(empirical_probabilities.round(6))

print("\nTotal transitions:", empirical_counts.values.sum())

print("\nTransition Probability Row Sums:")
print(empirical_probabilities.sum(axis=1).round(6))


# ==========================================
# STEP 12: SAVE OUTPUTS
# ==========================================

os.makedirs("trained_models", exist_ok=True)

empirical_counts.to_csv(
    "trained_models/transition_counts.csv"
)

empirical_probabilities.to_csv(
    "trained_models/transition_probability_matrix.csv"
)

joblib.dump(
    model,
    "trained_models/gaussian_hmm_v1.pkl"
)

out = training_df.copy()

out["raw_state"] = raw_states
out["state"] = named_states
out["state_name"] = out["state"].map(labels)

out.to_csv(
    "hourly_features_with_states.csv",
    index=False
)

print("\nAll transition matrices saved successfully.")
print("HMM model and states file saved successfully.")